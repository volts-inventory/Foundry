# First line of the manifest the materializer scaffolds from the tree's imports: an
# audit input, never an install source (its bare names are guesses, and installing a
# guessed name from a public index is dependency confusion).
SCAFFOLD_HEADER = "# Generated by Foundry — pinned dependency manifest for the release.\n"

_PIN = re.compile(r"([A-Za-z0-9][A-Za-z0-9._-]*)\s*(?:==\s*([A-Za-z0-9.+!_-]+))?")


def _satisfied(requirement: str) -> bool:
    """A bare name or exact ``==`` pin that Foundry's environment already has."""
    m = _PIN.fullmatch(requirement.strip())
    if m is None:
        return False
    try:
        have = im.version(m.group(1))
    except im.PackageNotFoundError:
        return False
    return m.group(2) is None or m.group(2) == have


def _requirement_lines(text: str) -> list[str]:
    lines = []
    for raw in text.splitlines():
        line = re.sub(r"(^|\s)#.*$", "", raw).strip()
        if line:
            lines.append(line)
    return lines


def declared_requirements(workdir: Path) -> tuple[str, ...]:
    """The ``pip install`` arguments for the project's declared dependencies
    (``requirements.txt``, ``[project].dependencies``); ``()`` when there is nothing
    Foundry's environment does not already satisfy."""
    args, lines = _declarations(workdir)
    if all(_satisfied(line) for line in lines):
        return ()
    return tuple(args)


def _declarations(workdir: Path) -> tuple[list[str], list[str]]:
    """The pip arguments and the requirement lines the project declares; a
    scaffolded requirements.txt declares nothing."""
    args: list[str] = []
    lines: list[str] = []
    req = workdir / "requirements.txt"
    if req.is_file():
        text = req.read_text(encoding="utf-8", errors="replace")
        declared = [] if text.startswith(SCAFFOLD_HEADER) else _requirement_lines(text)
        if declared:
            args += ["-r", "requirements.txt"]
            lines += declared
    pyproject = workdir / "pyproject.toml"
    if pyproject.is_file():
        try:
            project = tomllib.loads(pyproject.read_text(encoding="utf-8")).get("project")
        except (tomllib.TOMLDecodeError, UnicodeDecodeError):
            project = None  # the build/typecheck reports a broken pyproject itself
        deps = project.get("dependencies") if isinstance(project, dict) else None
        if isinstance(deps, list):
            named = [d for d in deps if isinstance(d, str) and d.strip()]
            args += named
            lines += named
    return args, lines


# Import names whose PyPI distribution is named differently.
_DIST_FOR_IMPORT = {
    "bs4": "beautifulsoup4", "cv2": "opencv-python", "dateutil": "python-dateutil",
    "dotenv": "python-dotenv", "jose": "python-jose", "jwt": "PyJWT",
    "multipart": "python-multipart", "PIL": "Pillow", "sklearn": "scikit-learn",
    "yaml": "PyYAML",
}
_NO_MODULE = re.compile(r"No module named '([A-Za-z_][\w.]*)'")


def undeclared_import_hints(output: str, workdir: Path) -> tuple[str, ...]:
    """One line per third-party module the output reports missing
    (``ModuleNotFoundError``) while the project declares no dependency at all — no
    manifest, or only the scaffold Foundry writes for the audit, which is never
    installed. Local modules and the standard library are left to the traceback."""
    if _declarations(workdir)[1]:
        return ()
    root = Path(workdir)
    scaffolded = (root / "requirements.txt").is_file() and (
        root / "requirements.txt"
    ).read_text(encoding="utf-8", errors="replace").startswith(SCAFFOLD_HEADER)
    try:
        installed = im.packages_distributions()
    except Exception:
        installed = {}
    hints: list[str] = []
    for name in dict.fromkeys(m.split(".", 1)[0] for m in _NO_MODULE.findall(output)):
        if (name in sys.stdlib_module_names or (root / name).is_dir()
                or (root / f"{name}.py").is_file()):
            continue
        dist = _DIST_FOR_IMPORT.get(name) or next(iter(installed.get(name, ())), name)
        hint = (
            f"the project imports `{name}` but declares no dependency on it: add "
            f"`{dist}` to requirements.txt (the Foundry-generated manifest is never "
            "installed)"
        )
        if scaffolded:
            hint += (
                "; requirements.txt still starts with Foundry's `"
                + SCAFFOLD_HEADER.strip()
                + "` header: rewrite it without that header so it is installed"
            )
        hints.append(hint)
    return tuple(hints)


# pip's words for a declaration that cannot be satisfied...
_PROJECT_FAULT = (
    "No matching distribution found for",
    "Could not find a version that satisfies the requirement",
    "ResolutionImpossible",
    "Invalid requirement",
    "has an invalid wheel",
    "Invalid wheel filename",
    "is not a supported wheel on this platform",
    "requires a different Python",
    "Could not open requirements file",
    # A declared sdist that does not build here (no wheel for this platform/Python,
    # a C extension needing a compiler or headers the host lacks): the fix is a
    # different dependency or version, which only the project can make.
    "Failed building wheel",
    "Failed to build",
    "subprocess-exited-with-error",
    "metadata-generation-failed",
    "error: command '",
    "fatal error: ",
)
# ...and for the network or index failing underneath it, which pip ALSO reports as
# "no matching distribution" once its retries run out.
_INFRA = (
    "Retrying (Retry(",
    "NewConnectionError",
    "ConnectTimeoutError",
    "ReadTimeoutError",
    "ProxyError",
    "SSLError",
    "Max retries exceeded",
    "Temporary failure in name resolution",
    "Name or service not known",
    "nodename nor servname",
    "Network is unreachable",
    "Connection refused",
    "Connection reset",
    "No space left on device",
)
_HTTP_5XX = re.compile(r"\b(?:HTTP error|status code:?)\s*5\d\d\b|\b5\d\d (?:Server Error|Service)")


def install_failure_is_project(output: str) -> bool:
    """True iff a failed ``pip install`` blames the project's declaration and nothing
    in the output points at the network, the index or the host."""
    if any(s in output for s in _INFRA) or _HTTP_5XX.search(output):
        return False
    return any(s in output for s in _PROJECT_FAULT)


_UNAVAILABLE = re.compile(
    r"(?:No matching distribution found for|"
    r"Could not find a version that satisfies the requirement)\s+(\S+)"
)


def unavailable_requirement_hints(output: str, workdir: Path) -> tuple[str, ...]:
    """One line per requirement pip found no distribution for, naming the manifest
    line that declares it. Only explains a failure pip already reported: a stdlib
    name is never rejected up front, since some of them also exist on PyPI."""
    req_file = workdir / "requirements.txt"
    req_lines = (
        req_file.read_text(encoding="utf-8", errors="replace").splitlines()
        if req_file.is_file()
        else []
    )
    hints: list[str] = []
    for requirement in dict.fromkeys(_UNAVAILABLE.findall(output)):
        m = _PIN.match(requirement)
        name = m.group(1) if m else requirement
        found = next(
            (
                (n, raw.strip())
                for n, raw in enumerate(req_lines, 1)
                if (pm := _PIN.match(re.sub(r"(^|\s)#.*$", "", raw).strip()))
                and pm.group(1).lower() == name.lower()
            ),
            None,
        )
        if name in sys.stdlib_module_names:
            fix = (
                f"delete the line `{found[1]}` (line {found[0]}) from requirements.txt"
                if found
                else f"remove `{requirement}` from the declared dependencies"
            )
            hints.append(
                f"`{name}` is part of Python's standard library, not a PyPI package: {fix}"
            )
        else:
            where = f" (requirements.txt line {found[0]}: `{found[1]}`)" if found else ""
            hints.append(
                f"no PyPI distribution matches `{requirement}`{where}: fix the name or "
                "the version, or remove it if the code does not import it"
            )
    return tuple(hints)


_NESTED = frozenset({"-r", "--requirement", "-c", "--constraint", "-e", "--editable"})


def manifest_digest(workdir: Path, requirements: tuple[str, ...]) -> str | None:
    """What a build venv's contents are a function of: the declared requirements,
    the ``requirements.txt`` bytes and the interpreter. ``None`` (never reused) when a
    requirement names local content (a path, a ``file:`` URL, a nested ``-r`` / ``-c``
    file), which can change while the manifest stays the same."""
    text = ""
    if requirements[:2] == ("-r", "requirements.txt"):
        text = (workdir / "requirements.txt").read_text(encoding="utf-8", errors="replace")
    for line in [*_requirement_lines(text), *requirements[2 if text else 0:]]:
        tokens = [t for t in re.split(r"[\s=]+", line) if t]
        if "file:" in line or tokens[0] in _NESTED or any(
            t.startswith((".", "/", "~")) for t in tokens
        ):
            return None
    return content_digest({"python": sys.version, "requirements": list(requirements),
                           "requirements.txt": text})


class PythonBuildEnv:
    """A build's venv and its install outcome, shared by that build's gates (and,
    when ``digest`` is set, by the run's later builds with the same manifests)."""

    def __init__(
        self, root: Path, requirements: tuple[str, ...], digest: str | None = None
    ) -> None:
        self.venv = root / "venv"
        self.scratch = root / "src"  # the install's throwaway copy of the workdir
        self.requirements = requirements
        self.digest = digest
        self.installed = False  # a successful install, reused while the digest matches
        self.ready = False  # set by this build's install step: may its gates run?
        self._lock = threading.Lock()

    @property
    def python(self) -> str:
        return str(self.venv / "bin" / "python")

    @property
    def site(self) -> str:
        return str(site_packages(self.venv))

    def install(self, workdir: Path, *, timeout_s: float) -> tuple[int, str, str]:
        with self._lock:
            if self.installed:
                self.ready = True
                note = f"reused this run's build venv for manifest {self.digest or ''}\n"
                return 0, note, ""
            shutil.rmtree(self.venv, ignore_errors=True)  # an earlier failed attempt
            build_python_env(self.venv)
            shutil.copytree(workdir, self.scratch, symlinks=True)
            try:
                rc, out, err = ground_untrusted(
                    (self.python, "-m", "pip", "install", "--disable-pip-version-check",
                     "--no-input", "--no-cache-dir", "--progress-bar", "off",
                     *self.requirements),
                    self.scratch,
                    network=True,
                    extra_env=activation_env(self.venv, os.environ.get("PATH", os.defpath)),
                    binds=((self.venv, True),),
                    timeout_s=timeout_s,
                )
            finally:
                shutil.rmtree(self.scratch, ignore_errors=True)
            self.installed = rc == 0 and self.digest is not None
            # A project-fault failure still lets the later gates judge the tree as it
            # is (as a build with no install would); an infra failure ERRORs them too.
            self.ready = rc == 0 or install_failure_is_project(out + err)
            return rc, out, err

    def run_env(self) -> dict[str, str]:
        """Env for a gate command over this build: the venv first on PATH, and its
        site-packages and python for the pinned harness."""
        self._require_install()
        return {**activation_env(self.venv, os.environ.get("PATH", os.defpath)),
                SITE_ENV: self.site, PYTHON_ENV: self.python}

    @property
    def binds(self) -> tuple[tuple[Path, bool], ...]:
        return ((self.venv, False),)

    def _require_install(self) -> None:
        if not self.ready:
            raise GroundingUnavailable(
                "the build's Python dependency install did not complete (see the build "
                "gate): this gate cannot run the project without its dependencies"
            )


class PythonEnvCache:
    """One run's gate venvs, one directory per manifest digest, so the run's wave
    checks and final gate install identical manifests once. Lives in a private temp
    dir (outside every workdir and tree id), removed by :meth:`close` or, failing
    that, when the cache is garbage-collected or the process exits."""

    def __init__(self) -> None:
        self._root: Path | None = None
        self._envs: dict[str, PythonBuildEnv] = {}
        self._lock = threading.Lock()
        self._cleanup: weakref.finalize[..., PythonEnvCache] | None = None

    def checkout(self, digest: str, requirements: tuple[str, ...]) -> PythonBuildEnv:
        with self._lock:
            if self._root is None:
                self._root = Path(tempfile.mkdtemp(prefix="foundry-gate-pyenvs-"))
                self._cleanup = weakref.finalize(self, shutil.rmtree, str(self._root), True)
            env = self._envs.get(digest)
            if env is None:
                env = PythonBuildEnv(self._root / digest[:32], requirements, digest)
                self._envs[digest] = env
            env.ready = False
            return env

    def close(self) -> None:
        if self._cleanup is not None:
            self._cleanup()


@contextlib.contextmanager
def python_build_env(
    workdir: Path, *, python: bool, cache: PythonEnvCache | None = None
) -> Iterator[PythonBuildEnv | None]:
    """The venv for a Python build that declares dependencies (else None): the run's
    venv for these manifests when ``cache`` is given and they are cacheable, else a
    fresh one removed when the build's gates are done."""
    requirements = declared_requirements(workdir) if python else ()
    if not requirements:
        yield None
        return
    digest = manifest_digest(workdir, requirements) if cache is not None else None
    if cache is not None and digest is not None:
        yield cache.checkout(digest, requirements)
        return
    with tempfile.TemporaryDirectory(prefix="foundry-gate-pyenv-") as root:
        yield PythonBuildEnv(Path(root), requirements)
