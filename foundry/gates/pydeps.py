"""The Python install step: a project's declared dependencies in a per-build venv.

A Python build whose manifest declares something Foundry's own environment does not
already provide gets a private venv (:func:`foundry.python_env.build_python_env`,
the same builder the agent's sandbox uses) OUTSIDE the workdir, so neither the tree
digest nor any snapshot sees it. BuildGate installs into it, the gate's only step
with network; build, test and smoke then run offline over it.

* **Install.** ``pip install`` runs confined (``ground_untrusted``, network through
  the egress relay) over a throwaway COPY of the workdir, with the venv bound
  writable: install-time code (an sdist's ``setup.py``) can write only the venv and
  the copy, never the tree the verdicts are attested against.
* **Project commands** (typecheck, smoke, a stack test command) run on the venv's
  python (its ``bin`` first on PATH), with the venv bound read-only.
* **The pinned pytest(-bdd) harness** keeps Foundry's own interpreter and gets the
  venv's site-packages only AFTER it has imported every trusted module
  (``FOUNDRY_GATE_SITE``), and as a plain path: no ``.pth`` an installed package
  ships runs before (or at all in) the harness. A dependency can't shadow pytest.

Nothing declared, or only what Foundry's environment already satisfies (the
materializer's own scaffolded manifest included), means no venv and no install.

Verdict on a failed install: FAIL when pip says the project's declaration is wrong
(unknown package, no matching version, conflicting pins, a malformed line) and no
network trouble shows in the output; otherwise ERROR (registry, proxy, DNS, build
toolchain). A FAIL latches the tree, so only the project's own mistake may produce
one.
"""

from __future__ import annotations

import contextlib
import importlib.metadata as im
import os
import re
import shutil
import tempfile
import tomllib
from collections.abc import Iterator
from pathlib import Path

from foundry.python_env import activation_env, build_python_env, site_packages

from .runner import GroundingUnavailable
from .sandbox import ground_untrusted

__all__ = [
    "SCAFFOLD_HEADER",
    "SITE_ENV",
    "PythonBuildEnv",
    "declared_requirements",
    "install_failure_is_project",
    "python_build_env",
]

# First line of the manifest the materializer scaffolds from the tree's imports: an
# audit input, never an install source (its bare names are guesses, and installing a
# guessed name from a public index is dependency confusion).
SCAFFOLD_HEADER = "# Generated by Foundry — pinned dependency manifest for the release.\n"
# The venv's site-packages, for the pinned harness to add after its trusted imports.
SITE_ENV = "FOUNDRY_GATE_SITE"

_PIN = re.compile(r"([A-Za-z0-9][A-Za-z0-9._-]*)\s*(?:==\s*([A-Za-z0-9.+!_-]+))?")


def _satisfied(requirement: str) -> bool:
    """A bare name or exact ``==`` pin that Foundry's environment already has."""
    m = _PIN.fullmatch(requirement.strip())
    if m is None:
        return False
    try:
        have = im.version(m.group(1))
    except im.PackageNotFoundError:
        return False
    return m.group(2) is None or m.group(2) == have


def _requirement_lines(text: str) -> list[str]:
    lines = []
    for raw in text.splitlines():
        line = re.sub(r"(^|\s)#.*$", "", raw).strip()
        if line:
            lines.append(line)
    return lines


def declared_requirements(workdir: Path) -> tuple[str, ...]:
    """The ``pip install`` arguments for the project's declared dependencies
    (``requirements.txt``, ``[project].dependencies``); ``()`` when there is nothing
    Foundry's environment does not already satisfy."""
    args: list[str] = []
    lines: list[str] = []
    req = workdir / "requirements.txt"
    if req.is_file():
        text = req.read_text(encoding="utf-8", errors="replace")
        declared = [] if text.startswith(SCAFFOLD_HEADER) else _requirement_lines(text)
        if declared:
            args += ["-r", "requirements.txt"]
            lines += declared
    pyproject = workdir / "pyproject.toml"
    if pyproject.is_file():
        try:
            project = tomllib.loads(pyproject.read_text(encoding="utf-8")).get("project")
        except (tomllib.TOMLDecodeError, UnicodeDecodeError):
            project = None  # the build/typecheck reports a broken pyproject itself
        deps = project.get("dependencies") if isinstance(project, dict) else None
        if isinstance(deps, list):
            named = [d for d in deps if isinstance(d, str) and d.strip()]
            args += named
            lines += named
    if all(_satisfied(line) for line in lines):
        return ()
    return tuple(args)


# pip's words for a declaration that cannot be satisfied...
_PROJECT_FAULT = (
    "No matching distribution found for",
    "Could not find a version that satisfies the requirement",
    "ResolutionImpossible",
    "Invalid requirement",
    "has an invalid wheel",
    "Invalid wheel filename",
    "is not a supported wheel on this platform",
    "requires a different Python",
    "Could not open requirements file",
)
# ...and for the network or index failing underneath it, which pip ALSO reports as
# "no matching distribution" once its retries run out.
_INFRA = (
    "Retrying (Retry(",
    "NewConnectionError",
    "ConnectTimeoutError",
    "ReadTimeoutError",
    "ProxyError",
    "SSLError",
    "Max retries exceeded",
    "Temporary failure in name resolution",
    "Name or service not known",
    "nodename nor servname",
    "Network is unreachable",
    "Connection refused",
    "Connection reset",
    "No space left on device",
)
_HTTP_5XX = re.compile(r"\b(?:HTTP error|status code:?)\s*5\d\d\b|\b5\d\d (?:Server Error|Service)")


def install_failure_is_project(output: str) -> bool:
    """True iff a failed ``pip install`` blames the project's declaration and nothing
    in the output points at the network, the index or the host."""
    if any(s in output for s in _INFRA) or _HTTP_5XX.search(output):
        return False
    return any(s in output for s in _PROJECT_FAULT)


class PythonBuildEnv:
    """One build's venv and its install outcome, shared by that build's gates."""

    def __init__(self, root: Path, requirements: tuple[str, ...]) -> None:
        self.venv = root / "venv"
        self.scratch = root / "src"  # the install's throwaway copy of the workdir
        self.requirements = requirements
        self.ready = False  # set by the install step: may the later gates run?

    @property
    def python(self) -> str:
        return str(self.venv / "bin" / "python")

    @property
    def site(self) -> str:
        return str(site_packages(self.venv))

    def install(self, workdir: Path, *, timeout_s: float) -> tuple[int, str, str]:
        build_python_env(self.venv)
        shutil.copytree(workdir, self.scratch, symlinks=True)
        try:
            rc, out, err = ground_untrusted(
                (self.python, "-m", "pip", "install", "--disable-pip-version-check",
                 "--no-input", "--no-cache-dir", "--progress-bar", "off",
                 *self.requirements),
                self.scratch,
                network=True,
                extra_env=activation_env(self.venv, os.environ.get("PATH", os.defpath)),
                binds=((self.venv, True),),
                timeout_s=timeout_s,
            )
        finally:
            shutil.rmtree(self.scratch, ignore_errors=True)
        # A project-fault failure still lets the later gates judge the tree as it is
        # (as a build with no install would); an infra failure makes them ERROR too.
        self.ready = rc == 0 or install_failure_is_project(out + err)
        return rc, out, err

    def run_env(self) -> dict[str, str]:
        """Env for a gate command over this build: the venv first on PATH, and its
        site-packages for the pinned harness."""
        self._require_install()
        return {**activation_env(self.venv, os.environ.get("PATH", os.defpath)),
                SITE_ENV: self.site}

    @property
    def binds(self) -> tuple[tuple[Path, bool], ...]:
        return ((self.venv, False),)

    def _require_install(self) -> None:
        if not self.ready:
            raise GroundingUnavailable(
                "the build's Python dependency install did not complete (see the build "
                "gate): this gate cannot run the project without its dependencies"
            )


@contextlib.contextmanager
def python_build_env(workdir: Path, *, python: bool) -> Iterator[PythonBuildEnv | None]:
    """A per-build venv for a Python build that declares dependencies (else None),
    removed when the build's gates are done."""
    requirements = declared_requirements(workdir) if python else ()
    if not requirements:
        yield None
        return
    with tempfile.TemporaryDirectory(prefix="foundry-gate-pyenv-") as root:
        yield PythonBuildEnv(Path(root), requirements)
