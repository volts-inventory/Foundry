"""Assemble per-service trees into ONE monorepo.

Takes the built services + the shared contract and produces a coherent repo:

    <out>/
      services/<name>/        each service's tree (code + docs)
      packages/contracts/     the shared OpenAPI + CONTRACT.md
      docker-compose.yml      one service per built service (+ postgres for data)
      Makefile                up / build / test across the workspace
      .github/workflows/ci.yml
      README.md               platform overview + service map
      PLATFORM-MANIFEST.json  the plan + per-service gate outcomes

The wiring (compose links, contract, README map) is what makes the pieces a
PLATFORM rather than N unrelated repos.
"""

from __future__ import annotations

import json
import os
import shutil

from foundry.platform.schema import PlatformPlan, ServiceResult

# Conventional container port per role for the generated compose file.
_PORT: dict[str, int] = {"web": 3000, "backend": 8000, "worker": 0,
                         "data": 5432, "game": 0}


def _copy_tree(src: str, dst: str) -> None:
    os.makedirs(dst, exist_ok=True)
    for root, _dirs, files in os.walk(src):
        rel = os.path.relpath(root, src)
        target = os.path.join(dst, rel) if rel != "." else dst
        os.makedirs(target, exist_ok=True)
        for f in files:
            shutil.copy2(os.path.join(root, f), os.path.join(target, f))


def _compose(plan: PlatformPlan, results: list[ServiceResult]) -> str:
    built = {r.name for r in results if r.source_root}
    lines = ["# Generated by foundry.platform — one container per built service.",
             "services:"]
    for svc in plan.services:
        if svc.name not in built:
            continue
        if svc.role == "game":
            continue                          # a native game, not a container
        if svc.role == "data":
            # Keyed on svc.name (NOT a hardcoded "data") so a planner that names
            # the data service differently stays consistent with the tree at
            # services/<name>/ and with other services' depends_on references.
            port = _PORT["data"]
            lines += [
                f"  {svc.name}:",
                "    image: postgres:16",
                "    environment:",
                "      POSTGRES_PASSWORD: dev",
                "      POSTGRES_DB: app",
                "    ports:", f'      - "{port}:{port}"',
            ]
            dep = [d for d in svc.depends_on if d in built]
            if dep:
                lines.append("    depends_on:")
                lines += [f"      - {d}" for d in dep]
            continue
        lines += [
            f"  {svc.name}:",
            f"    build: ./services/{svc.name}",
        ]
        if _PORT.get(svc.role):
            lines += ["    ports:", f'      - "{_PORT[svc.role]}:{_PORT[svc.role]}"']
        if svc.depends_on:
            dep = [d for d in svc.depends_on if d in built]
            if dep:
                lines.append("    depends_on:")
                lines += [f"      - {d}" for d in dep]
    return "\n".join(lines) + "\n"


def _run_section(plan: PlatformPlan, results: list[ServiceResult]) -> list[str]:
    """How to run THIS platform — a game runs natively; services run via compose."""
    built = {r.name for r in results if r.source_root}
    game = next((s for s in plan.services if s.role == "game" and s.name in built), None)
    has_services = any(s.role != "game" and s.name in built for s in plan.services)
    lines = ["## Run", ""]
    if game:
        lines += [
            "The game runs natively in its engine (see `services/game/`):",
            "",
            "```bash",
            "love services/game        # LÖVE (Love2D) — or follow services/game/README.md",
            "```",
            "",
        ]
    if has_services:
        lines += [
            "```bash",
            "docker compose up --build      # start every service",
            "make test                      # run each service's tests",
            "```",
            "",
        ]
    return lines


def _readme(plan: PlatformPlan, results: list[ServiceResult]) -> str:
    by_name = {r.name: r for r in results}
    rows = ["| Service | Role | Talks to | Build |", "|---|---|---|---|"]
    for s in plan.services:
        r = by_name.get(s.name)
        status = "—"
        if r:
            status = "✓ pass" if r.passed else ("◐ draft" if r.source_root else "✗ no output")
        deps = ", ".join(s.depends_on) or "—"
        rows.append(f"| `{s.name}` | {s.role} | {deps} | {status} |")
    return "\n".join([
        f"# {plan.name}",
        "",
        f"> {plan.request}",
        "",
        "A multi-service platform composed by **foundry.platform**: each service was "
        "built by the Foundry factory against one shared API contract, then stitched "
        "into this monorepo.",
        "",
        "## Services",
        "",
        *rows,
        "",
        "## Layout",
        "",
        "- `services/<name>/` — each service (code + its own `docs/`).",
        "- `packages/contracts/` — the shared API contract every service is built to.",
        "- `docker-compose.yml` — bring the whole platform up locally.",
        "",
        *_run_section(plan, results),
        "The contract in `packages/contracts/CONTRACT.md` is the source of truth for "
        "the seams between services — change it there, then re-build the affected services.",
        "",
    ])


def _makefile(plan: PlatformPlan, results: list[ServiceResult]) -> str:
    built = [r.name for r in results if r.source_root]
    lines = [
        ".PHONY: up build test",
        "up:\n\tdocker compose up --build",
        "build:\n\tdocker compose build",
    ]
    test_cmds = "\n".join(
        f'\t-cd services/{n} && (make test 2>/dev/null || pytest -q 2>/dev/null || true)'
        for n in built
    )
    lines.append("test:\n" + (test_cmds or "\t@echo 'no services built'"))
    return "\n".join(lines) + "\n"


def _ci(plan: PlatformPlan, results: list[ServiceResult]) -> str:
    built = [r.name for r in results if r.source_root]
    matrix = ", ".join(f'"{n}"' for n in built) or '""'
    return "\n".join([
        "name: ci",
        "on: [push, pull_request]",
        "jobs:",
        "  test:",
        "    runs-on: ubuntu-latest",
        "    strategy:",
        "      matrix:",
        f"        service: [{matrix}]",
        "    steps:",
        "      - uses: actions/checkout@v4",
        "      - name: test ${{ matrix.service }}",
        "        run: cd services/${{ matrix.service }} && (make test || pytest -q || true)",
        "",
    ])


def _manifest(plan: PlatformPlan, results: list[ServiceResult]) -> str:
    raw_paths = plan.contract.get("paths")
    paths = sorted(raw_paths.keys()) if isinstance(raw_paths, dict) else []
    return json.dumps({
        "platform": plan.name,
        "request": plan.request,
        "services": [
            {"name": r.name, "role": r.role, "passed": r.passed, "phase": r.phase,
             "is_draft": r.is_draft, "gates": r.gates, "path": f"services/{r.name}"}
            for r in results
        ],
        "contract": {"entities": plan.contract.get("x-entities", []), "paths": paths},
    }, indent=2, sort_keys=True) + "\n"


def stitch_monorepo(
    plan: PlatformPlan,
    results: list[ServiceResult],
    contract_files: dict[str, str],
    out_dir: str,
) -> None:
    """Write the stitched monorepo to ``out_dir``."""
    os.makedirs(out_dir, exist_ok=True)

    # 1. each service's tree -> services/<name>/
    for r in results:
        if not r.source_root:
            continue
        _copy_tree(r.source_root, os.path.join(out_dir, "services", r.name))

    # 2. shared contract -> packages/contracts/
    contracts_dir = os.path.join(out_dir, "packages", "contracts")
    os.makedirs(contracts_dir, exist_ok=True)
    for rel, content in contract_files.items():
        with open(os.path.join(contracts_dir, rel), "w", encoding="utf-8") as fh:
            fh.write(content)

    # 3. workspace wiring
    writes = {
        "docker-compose.yml": _compose(plan, results),
        "Makefile": _makefile(plan, results),
        "README.md": _readme(plan, results),
        "PLATFORM-MANIFEST.json": _manifest(plan, results),
        os.path.join(".github", "workflows", "ci.yml"): _ci(plan, results),
    }
    for rel, content in writes.items():
        path = os.path.join(out_dir, rel)
        os.makedirs(os.path.dirname(path) or out_dir, exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
